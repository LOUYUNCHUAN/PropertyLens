# ── Lifespan: load artefacts once at startup ──────────────────────
@asynccontextmanager
async def lifespan(app: FastAPI):
    from backend.hybrid_inference import HybridPredictWrapper, configure, load_bundle

    print("Loading artefacts...")
    print(f"   Artefacts: {ARTIFACTS_ROOT}")
    print(f"   Hybrid XAI: {HYBRID_XAI_DIR}")
    print(f"   Feature tables: {FEATURE_LAYER_OUTPUTS}")
    if FEATURE_TABLE_CSV_RESOLVED:
        print(f"   Feature table (pinned): {FEATURE_TABLE_CSV_RESOLVED}")
    else:
        print("   Feature table: latest hdb_feature_table_*.csv under outputs (set PROPERTYLENS_FEATURE_TABLE_CSV to pin)")

    configure(ARTIFACTS_ROOT, FEATURE_LAYER_OUTPUTS, feature_table_csv=FEATURE_TABLE_CSV_RESOLVED)

    bundle = load_bundle()
    state.hybrid_bundle = bundle
    state.feature_cols = list(bundle["feature_columns"])
    state.xgb_model = HybridPredictWrapper(bundle)

    state.cbr_tree = joblib.load(HYBRID_XAI_DIR / "cbr_index.joblib")
    state.cbr_scaler = joblib.load(HYBRID_XAI_DIR / "cbr_scaler.joblib")
    state.cbr_df = pd.read_parquet(HYBRID_XAI_DIR / "cbr_training_data.parquet")

    with open(HYBRID_XAI_DIR / "cbr_features.json") as f:
        state.cbr_feature_cols = json.load(f)

    with open(HYBRID_XAI_DIR / "global_shap_cache.json") as f:
        state.global_shap = json.load(f)

    # Optional: per-cluster global SHAP importance + baselines for Analyst view.
    # Generated by notebooks/04_xai_layer/04_hybrid_xai_train.ipynb.
    by_cluster_path = HYBRID_XAI_DIR / "global_shap_by_cluster.json"
    if by_cluster_path.exists():
        with open(by_cluster_path) as f:
            state.global_shap_by_cluster = json.load(f)

    with open(HYBRID_XAI_DIR / "rules.json") as f:
        state.rules = json.load(f)

    lime_data = joblib.load(HYBRID_XAI_DIR / "lime_training_data.joblib")
    state.lime_explainer = lime.lime_tabular.LimeTabularExplainer(
        training_data=lime_data["training_data"],
        feature_names=lime_data["feature_names"],
        mode="regression",
        random_state=42,
    )

    meta_path = ARTIFACTS_ROOT / "hybrid_cluster_meta.json"
    if not meta_path.exists():
        raise RuntimeError(
            f"Required model metadata missing: {meta_path}. "
            "Run 03_ml_layer_hybrid/02_hybrid_ensemble.ipynb to regenerate."
        )
    with open(meta_path) as f:
        state.model_meta = json.load(f)
    if not state.model_meta.get("test_metrics"):
        raise RuntimeError(
            f"{meta_path} is missing 'test_metrics'. Retrain the hybrid ensemble."
        )

    print("✅ Hybrid cluster artefacts loaded")
    print(f"   Features: {len(state.feature_cols)}")
    print(f"   CBR cases: {len(state.cbr_df):,}")
    try:
        from backend.db import SessionLocal, init_db
        from backend.auth_routes import ensure_demo_user

        init_db()
        _sess = SessionLocal()
        try:
            ensure_demo_user(_sess)
        finally:
            _sess.close()
        print("✅ User history DB initialized (SQLite / DATABASE_URL)")
    except Exception as e:
        print(f"⚠️ User history DB init failed: {e}")
    yield
    print("Shutting down")


