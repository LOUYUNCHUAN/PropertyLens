@app.get("/api/kb/policy-impact/{town}")
def get_policy_impact(town: str):
    """Return all policies that affected this town, sorted by year descending."""
    town_upper = town.upper()
    town_title = town.title()

    # Try Neo4j first; fall back to hardcoded list
    kb_source = "hardcoded"
    confirmed_names: set[str] | None = None

    try:
        import os
        from neo4j import GraphDatabase
        uri  = os.environ.get("NEO4J_URI", "bolt://localhost:7687")
        user = os.environ.get("NEO4J_USER", "neo4j")
        pwd  = os.environ.get("NEO4J_PASSWORD", "password")
        driver = GraphDatabase.driver(uri, auth=(user, pwd))
        with driver.session() as session:
            result = session.run(
                "MATCH (p:Policy)-[:AFFECTED]->(t:Town {name: $town}) "
                "RETURN p.name AS name",
                town=town_upper,
            )
            confirmed_names = {r["name"] for r in result}
        driver.close()
        if confirmed_names:
            kb_source = "neo4j"
    except Exception:
        pass  # graceful fallback

    policies = []
    for meta in _POLICY_META:
        if confirmed_names is not None and meta["name"] not in confirmed_names:
            continue
        explanation = _POLICY_EXPLANATIONS.get(meta["name"], "")
        policies.append({
            "name":        meta["name"],
            "year":        meta["year"],
            "impact":      meta["impact"],
            "explanation": explanation.format(town=town_title),
        })

    positive = sum(1 for p in policies if p["impact"] == "positive")
    negative = sum(1 for p in policies if p["impact"] == "negative")
    if positive > negative:
        net_sentiment = "cautiously positive"
    elif negative > positive:
        net_sentiment = "policy headwinds present"
    else:
        net_sentiment = "mixed policy environment"

    return {
        "town":          town_upper,
        "policies":      policies,
        "net_sentiment": net_sentiment,
        "kb_source":     kb_source,
    }


